"""Compose the launcher / application icon from the PHS Radio logo.

The logo itself stays generated by tools/generate-app-icon.cpp (the same vector
paths Windows draws). This script only puts it on the aqua tile that a launcher
or a desktop shortcut actually needs, then emits the Android mipmaps and the
Windows .ico from that single artwork.

    python tools/make-icons.py
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOGO = os.path.join(ROOT, "android", "app", "src", "main", "res", "drawable-nodpi", "logo_phs.png")
RES = os.path.join(ROOT, "resources")
ANDROID_RES = os.path.join(ROOT, "android", "app", "src", "main", "res")

SIZE = 1024
RADIUS = 232
TOP = (30, 132, 165)      # mid cyan, upper left
BOTTOM = (5, 30, 48)      # deep sea, lower right
RIM = (234, 253, 255)


def diagonal_gradient(size, top, bottom):
    image = Image.new("RGB", (size, size))
    pixels = image.load()
    for y in range(size):
        for x in range(size):
            t = (x + y) / (2.0 * (size - 1))
            pixels[x, y] = (
                int(top[0] + (bottom[0] - top[0]) * t),
                int(top[1] + (bottom[1] - top[1]) * t),
                int(top[2] + (bottom[2] - top[2]) * t),
            )
    return image


def radial_highlight(size, center, radius, color, strength):
    layer = Image.new("L", (size, size), 0)
    draw = ImageDraw.Draw(layer)
    steps = 48
    for i in range(steps, 0, -1):
        r = radius * i / steps
        alpha = int(strength * (1.0 - i / steps) ** 1.6)
        draw.ellipse([center[0] - r, center[1] - r, center[0] + r, center[1] + r], fill=alpha)
    layer = layer.filter(ImageFilter.GaussianBlur(size // 90))
    tint = Image.new("RGB", (size, size), color)
    return tint, layer


def compose():
    tile = diagonal_gradient(SIZE, TOP, BOTTOM).convert("RGBA")

    tint, mask = radial_highlight(SIZE, (SIZE * 0.30, SIZE * 0.26), SIZE * 0.62, (170, 240, 255), 95)
    tile = Image.composite(tint, tile, mask)

    # Rounded square silhouette.
    shape = Image.new("L", (SIZE, SIZE), 0)
    ImageDraw.Draw(shape).rounded_rectangle([0, 0, SIZE - 1, SIZE - 1], RADIUS, fill=255)
    tile.putalpha(shape)

    logo = Image.open(LOGO).convert("RGBA")
    target = int(SIZE * 0.78)
    logo = logo.resize((target, target), Image.LANCZOS)

    # Soft drop shadow so the pearl P lifts off the tile.
    shadow = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    offset = int(SIZE * 0.018)
    shadow.paste((4, 22, 34, 120), (int((SIZE - target) / 2) + offset, int((SIZE - target) / 2) + offset),
                 logo.split()[3])
    shadow = shadow.filter(ImageFilter.GaussianBlur(SIZE // 48))
    tile.alpha_composite(shadow)
    tile.alpha_composite(logo, (int((SIZE - target) / 2), int((SIZE - target) / 2)))

    # Rim light along the tile edge.
    rim = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    ImageDraw.Draw(rim).rounded_rectangle([3, 3, SIZE - 4, SIZE - 4], RADIUS - 3,
                                          outline=RIM + (52,), width=max(2, SIZE // 170))
    tile.alpha_composite(rim)
    return tile


def emit(icon):
    icon.save(os.path.join(RES, "app-icon-1024.png"))

    sizes = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
    for density, size in sizes.items():
        folder = os.path.join(ANDROID_RES, "mipmap-" + density)
        os.makedirs(folder, exist_ok=True)
        icon.resize((size, size), Image.LANCZOS).save(os.path.join(folder, "ic_launcher.png"))

    icon.save(os.path.join(RES, "app.ico"),
              sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    print("wrote app-icon-1024.png, app.ico and 5 mipmap densities")


if __name__ == "__main__":
    if not os.path.exists(LOGO):
        raise SystemExit("logo_phs.png is missing; run tools/generate-app-icon first")
    emit(compose())
